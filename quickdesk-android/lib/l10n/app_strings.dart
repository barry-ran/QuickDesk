  static String t(String key, [Map<String, Object?>? params]) {
    final table = locale == AppLocale.zh ? _zh : _en;
    var s = table[key] ?? _zh[key] ?? key;
    if (params != null) {
      params.forEach((k, v) {
        s = s.replaceAll('{$k}', '${v ?? ''}');
      });
    }
    return s;
